"""PostgreSQL / Supabase backend adapter.

The rest of the application is written against the ``sqlite3`` DB-API:

* qmark ``?`` placeholders,
* rows addressable **both** by position (``row[0]``) and by column name
  (``row['col']``), and
* a handful of SQLite-only SQL constructs (``AUTOINCREMENT``,
  ``INSERT OR IGNORE``, ``CREATE VIEW IF NOT EXISTS``,
  ``ALTER TABLE ... ADD COLUMN``, ``DEFAULT CURRENT_TIMESTAMP`` on TEXT columns,
  case-insensitive ``LIKE``).

:class:`Connection` wraps ``psycopg`` (psycopg 3) so that code written for
SQLite keeps working unchanged, and :func:`to_postgres` rewrites the SQLite-only
constructs into their PostgreSQL equivalents.  There is no literal ``%`` in any
SQL string in this codebase, so replacing ``?`` with ``%s`` is safe.

``psycopg`` is imported lazily (only when a Postgres connection is actually
opened) so SQLite-only installs never need it.
"""
import re
import threading
import time

_POSTGRES_URL = re.compile(r'^postgres(?:ql)?://', re.I)


def is_postgres_url(value):
    """True when ``value`` looks like a PostgreSQL/Supabase connection string."""
    return bool(value) and bool(_POSTGRES_URL.match(str(value)))


# --------------------------------------------------------------------------- #
# SQL translation (SQLite -> PostgreSQL)
# --------------------------------------------------------------------------- #
_ISO_TEXT_DEFAULT = "to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD\"T\"HH24:MI:SS')"


def to_postgres(sql):
    """Rewrite one SQL statement from SQLite to PostgreSQL dialect.

    Idempotent and safe to run on statements that are already PostgreSQL, so the
    same migration list can drive either backend.
    """
    s = sql

    # --- placeholders -----------------------------------------------------
    # Done last so the regex work above sees the original text.

    # --- DDL --------------------------------------------------------------
    # AUTOINCREMENT -> identity column
    s = re.sub(r'INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT',
               'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', s, flags=re.I)
    # bare `id INTEGER PRIMARY KEY` (legacy v1 tables) -> identity column
    s = re.sub(r'\bid\s+INTEGER\s+PRIMARY\s+KEY\b',
               'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', s, flags=re.I)
    # TEXT timestamp columns: keep the exact string format the app writes.
    s = re.sub(r'DEFAULT\s+CURRENT_TIMESTAMP',
               'DEFAULT (' + _ISO_TEXT_DEFAULT + ')', s, flags=re.I)
    # views have no IF NOT EXISTS in PostgreSQL
    s = re.sub(r'CREATE\s+VIEW\s+IF\s+NOT\s+EXISTS', 'CREATE OR REPLACE VIEW', s, flags=re.I)
    # ADD COLUMN IF NOT EXISTS keeps migrations idempotent
    s = re.sub(r'ADD\s+COLUMN(?!\s+IF\s+NOT\s+EXISTS)',
               'ADD COLUMN IF NOT EXISTS', s, flags=re.I)

    # --- DML --------------------------------------------------------------
    had_ignore = bool(re.search(r'INSERT\s+OR\s+IGNORE', s, re.I))
    if had_ignore:
        s = re.sub(r'INSERT\s+OR\s+IGNORE', 'INSERT', s, flags=re.I)
        if not re.search(r'\bON\s+CONFLICT\b', s, re.I):
            s = s.rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'

    # SQLite LIKE is case-insensitive for ASCII; PostgreSQL's is not.
    s = re.sub(r'\bLIKE\b', 'ILIKE', s)

    # --- placeholders (last) ---------------------------------------------
    s = s.replace('?', '%s')
    return s


def with_returning(sql, column='id'):
    """Ensure an INSERT returns ``column`` (used to recover the new row id)."""
    if re.search(r'\bRETURNING\b', sql, re.I):
        return sql
    return sql.rstrip().rstrip(';') + f' RETURNING {column}'


# --------------------------------------------------------------------------- #
# psycopg-backed connection/cursor/row that mimic sqlite3 ergonomics
# --------------------------------------------------------------------------- #
class Row:
    """A result row addressable by index (``row[0]``) *and* by name (``row['x']``)."""

    __slots__ = ('_data', '_values')

    def __init__(self, data, order):
        self._data = data
        self._values = [data[k] for k in order]

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self._values[key]
        return self._data[key]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __contains__(self, key):
        return key in self._data

    def keys(self):
        return list(self._data.keys())

    def values(self):
        return list(self._values)

    def items(self):
        return list(self._data.items())

    def get(self, key, default=None):
        return self._data.get(key, default)

    def __repr__(self):  # pragma: no cover - debugging aid
        return f'Row({self._data!r})'


class Cursor:
    """Thin wrapper over a psycopg cursor returning :class:`Row` objects."""

    def __init__(self, cur, order):
        self._cur = cur
        self._order = order
        self.lastrowid = None

    def _wrap(self, row):
        return None if row is None else Row(row, self._order)

    def fetchone(self):
        return self._wrap(self._cur.fetchone())

    def fetchall(self):
        return [self._wrap(r) for r in self._cur.fetchall()]

    def __iter__(self):
        for r in self._cur:
            yield self._wrap(r)

    def close(self):
        self._cur.close()


class Connection:
    """A sqlite3-like connection backed by psycopg 3.

    ``prepare_threshold=None`` disables psycopg's automatic server-side
    prepared statements, which are not supported by Supabase's transaction-mode
    connection pooler (port 6543).
    """

    def __init__(self, dsn):
        import psycopg
        from psycopg.rows import dict_row

        self._dict_row = dict_row
        self._conn = psycopg.connect(dsn, row_factory=dict_row,
                                     prepare_threshold=None, connect_timeout=15)

    def _cursor(self, sql, args):
        cur = self._conn.cursor(row_factory=self._dict_row)
        cur.execute(to_postgres(sql), args if args else None)
        order = [d.name for d in cur.description] if cur.description else []
        return Cursor(cur, order)

    def execute(self, sql, args=()):
        return self._cursor(sql, args)

    def executemany(self, sql, seq):
        cur = self._conn.cursor(row_factory=self._dict_row)
        cur.executemany(to_postgres(sql), list(seq))
        return Cursor(cur, [])

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()


# --------------------------------------------------------------------------- #
# Connection reuse
# --------------------------------------------------------------------------- #
# Opening a Postgres connection to Supabase costs several network round trips
# (TCP + TLS + auth).  Doing that on every request is the main reason the site
# feels slow.  A warm server process / serverless instance keeps one connection
# per thread and reuses it; it is rolled back after every request so no
# transaction state leaks between users.
_local = threading.local()
_IDLE_PING_SECONDS = 20


def _usable(conn):
    raw = conn._conn
    return not (raw.closed or getattr(raw, 'broken', False))


def shared_connection(dsn):
    """Return this thread's cached connection to ``dsn`` (opening it if needed)."""
    cached = getattr(_local, 'conn', None)
    if cached is not None and getattr(_local, 'dsn', None) == dsn and _usable(cached):
        if time.time() - getattr(_local, 'last_used', 0) > _IDLE_PING_SECONDS:
            try:                      # the pooler may have dropped an idle link
                cached.execute('SELECT 1').close()
                cached.rollback()
            except Exception:
                _discard(cached)
                cached = None
        if cached is not None:
            _local.last_used = time.time()
            return cached
    elif cached is not None:
        _discard(cached)
    conn = Connection(dsn)
    _local.conn, _local.dsn, _local.last_used = conn, dsn, time.time()
    return conn


def _discard(conn):
    try:
        conn.close()
    except Exception:
        pass
    _local.conn = None


def release(conn):
    """End-of-request: roll back leftovers and keep the connection for reuse."""
    try:
        if _usable(conn):
            conn.rollback()
            _local.last_used = time.time()
            return
    except Exception:
        pass
    if getattr(_local, 'conn', None) is conn:
        _discard(conn)
    else:
        try:
            conn.close()
        except Exception:
            pass
